#!/usr/bin/env python3
"""Generate compile-time source policies for Dart and Go from one reviewed file."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CAPABILITIES = ('search', 'pagedSearch', 'suggestions', 'recommendations', 'danmaku', 'devices', 'rankings', 'account', 'metadata', 'seasons')
FLAGS = ('standard', 'adult', 'allowEmptyCatalog', 'noHostRotation', 'browserFingerprint')
FIELDS = {'id', 'name', 'capabilities', 'browserHosts', 'dnsHosts', *FLAGS}
GO_NAMES = {'standard': 'Standard', 'adult': 'Adult', 'allowEmptyCatalog': 'AllowEmptyCatalog', 'noHostRotation': 'NoHostRotation', 'browserFingerprint': 'BrowserFingerprint'}
GO_LISTS = (('capabilities', 'Capabilities'), ('browserHosts', 'BrowserHosts'), ('dnsHosts', 'DNSHosts'))
DART_WIDTH = 80


def load_sources(path=ROOT / 'config/source_capabilities.json'):
    data = json.loads(path.read_text(encoding='utf-8'))
    if data.get('format') != 1 or not isinstance(data.get('sources'), list):
        raise ValueError('invalid source capability format')
    ids, hosts = set(), set()
    for row in data['sources']:
        if not isinstance(row, dict) or set(row) - FIELDS:
            raise ValueError('unknown source field')
        source = row.get('id', '')
        if not re.fullmatch(r'[a-z0-9][a-z0-9_-]{0,31}', source) or source in ids:
            raise ValueError('invalid or duplicate source id')
        ids.add(source)
        if not isinstance(row.get('name'), str) or not row['name'].strip():
            raise ValueError('missing source name')
        capabilities = row.get('capabilities', [])
        if not isinstance(capabilities, list) or len(set(capabilities)) != len(capabilities) or set(capabilities) - set(CAPABILITIES):
            raise ValueError('invalid source capabilities')
        if 'pagedSearch' in capabilities and 'search' not in capabilities:
            raise ValueError('paged search requires search')
        for flag in FLAGS:
            if flag in row and not isinstance(row[flag], bool):
                raise ValueError('source flag must be boolean')
        if row.get('adult') and row.get('standard'):
            raise ValueError('restricted source cannot be in standard edition')
        for field in ('browserHosts', 'dnsHosts'):
            names = row.get(field, [])
            if not isinstance(names, list) or len(set(names)) != len(names):
                raise ValueError('invalid host list')
            for host in names:
                if not isinstance(host, str) or not re.fullmatch(r'(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}', host):
                    raise ValueError('hosts must be explicit lowercase DNS names')
                key = (field, host)
                if key in hosts:
                    raise ValueError('host belongs to multiple sources')
                hosts.add(key)
        if bool(row.get('browserHosts')) != bool(row.get('browserFingerprint')):
            raise ValueError('browser fingerprint and host list must agree')
    return data['sources']


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def braced(lines):
    return '{\n' + '\n'.join(lines) + '\n}' if lines else '{}'


def dart_source(rows):
    lines = []
    for row in rows:
        # The only variable Dart tokens are validated ASCII IDs and feature names.
        # Keep the call flat if it fits; otherwise wrap the args, then the set.
        start = f'  {quote(row["id"])}: SourceCapabilities('
        flags = [f'{f}: {str(row.get(f, False)).lower()}' for f in ('standard', 'adult')]
        features = [quote(c) for c in row.get('capabilities', [])]
        feature_arg = 'features: {' + ', '.join(features) + '}'
        flat = start + ', '.join([*flags, feature_arg]) + '),'
        if len(flat) <= DART_WIDTH:
            lines.append(flat)
            continue
        lines.append(start)
        lines.extend(f'    {flag},' for flag in flags)
        if len(f'    {feature_arg},') <= DART_WIDTH:
            lines.append(f'    {feature_arg},')
        else:
            lines.append('    features: {')
            lines.extend(f'      {feature},' for feature in features)
            lines.append('    },')
        lines.append('  ),')
    return '''// Generated by scripts/generate_source_capabilities.py; do not edit.

class SourceCapabilities {
  const SourceCapabilities({
    this.standard = false,
    this.adult = false,
    this.features = const {},
  });
  final bool standard;
  final bool adult;
  final Set<String> features;
}

const sourceCapabilities = <String, SourceCapabilities>''' + braced(lines) + ''';

bool sourceHasCapability(String source, String capability) =>
    sourceCapabilities[source]?.features.contains(capability) ?? false;
'''


def go_columns(indent, fields):
    """gofmt aligns each contiguous group of single-line fields independently."""
    width = max(len(key) for key, _ in fields)
    return [f'{indent}{key:<{width}} {value}' for key, value in fields]


def go_source(rows):
    lines = ['// Code generated by scripts/generate_source_capabilities.py; DO NOT EDIT.', 'package core', '', 'type nativeSourceDescriptor struct {']
    fields = [('ID', 'string'), ('Name', 'string')]
    fields += [(GO_NAMES[f], 'bool') for f in FLAGS]
    fields += [(name, '[]string') for _, name in GO_LISTS]
    lines += go_columns('\t', fields)
    entries = []
    for row in rows:
        values = [('ID', quote(row['id'])), ('Name', quote(row['name']))]
        values += [(GO_NAMES[f], 'true') for f in FLAGS if row.get(f)]
        for field, name in GO_LISTS:
            if row.get(field):
                values.append((name, '[]string{' + ', '.join(map(quote, row[field])) + '}'))
        entries.append('\t{')
        entries += go_columns('\t\t', [(key + ':', value + ',') for key, value in values])
        entries.append('\t},')
    lines += ['}', '', 'var nativeSourceDescriptors = []nativeSourceDescriptor' + braced(entries), '']
    return '\n'.join(lines)


def generated(rows):
    return {'lib/source_capabilities.g.dart': dart_source(rows), 'native/core/source_capabilities_generated.go': go_source(rows)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in generated(load_sources()).items():
        file = ROOT / name
        if args.check:
            if not file.exists() or file.read_bytes() != content.encode('utf-8'):
                raise SystemExit(f'Generated source policy differs: {name}')
        else:
            file.write_text(content, encoding='utf-8', newline='\n')
    print('Source capability outputs ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
